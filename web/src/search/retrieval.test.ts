import { describe, expect, it } from "vitest";
import golden from "./golden_retrieval.json";

// minimal shape of node's process.cwd used below (no @types/node in this
// project; vitest always provides the real global)
declare const process: { cwd: () => string };
import {
  arcLengthResample,
  coarseShortlist,
  ensureCcw,
  harmonicAmplitudes,
  normalizeContour,
  queryFeatureVector,
  shapeMetrics,
  smoothCyclic,
  type Point,
} from "./retrieval";

const g = golden as unknown as {
  input: {
    query_trace: Point[];
    n_points: number;
    n_harmonics: number;
    smoothing_sigma: number;
  };
  expected: {
    resampled: Point[];
    smoothed: Point[];
    normalized: Point[];
    fourier_amplitudes: number[];
    geometry_stats: number[];
    query_vector: number[];
  };
  library: {
    n_candidates: number;
    coarse: {
      shortlist_rows: number[];
      shortlist_distances: number[];
      candidate_ids: string[];
    };
  };
  tolerances: Record<string, string | number>;
};

const rel = (a: number, b: number): number =>
  Math.abs(a - b) / Math.max(1e-300, Math.abs(b));

describe("static retrieval chain vs the Python golden vectors", () => {
  it("resamples the trace on the same arc-length grid", () => {
    const ordered = ensureCcw(g.input.query_trace);
    const out = arcLengthResample(ordered, g.input.n_points);
    expect(out.length).toBe(g.expected.resampled.length);
    for (let i = 0; i < out.length; i++) {
      expect(Math.abs(out[i][0] - g.expected.resampled[i][0])).toBeLessThan(1e-9);
      expect(Math.abs(out[i][1] - g.expected.resampled[i][1])).toBeLessThan(1e-9);
    }
  });

  it("smooths with the same cyclic Gaussian response", () => {
    const out = smoothCyclic(g.expected.resampled, g.input.smoothing_sigma);
    for (let i = 0; i < out.length; i++) {
      expect(Math.abs(out[i][0] - g.expected.smoothed[i][0])).toBeLessThan(1e-9);
      expect(Math.abs(out[i][1] - g.expected.smoothed[i][1])).toBeLessThan(1e-9);
    }
  });

  it("normalizes identically", () => {
    const out = normalizeContour(g.expected.smoothed);
    for (let i = 0; i < out.length; i++) {
      expect(rel(out[i][0], g.expected.normalized[i][0])).toBeLessThan(1e-9);
      expect(rel(out[i][1], g.expected.normalized[i][1])).toBeLessThan(1e-9);
    }
  });

  it("computes the same 16 Fourier amplitudes", () => {
    const out = harmonicAmplitudes(g.expected.normalized, g.input.n_harmonics);
    expect(out.length).toBe(g.expected.fourier_amplitudes.length);
    for (let i = 0; i < out.length; i++) {
      expect(rel(out[i], g.expected.fourier_amplitudes[i])).toBeLessThan(1e-9);
    }
  });

  it("computes the same four geometry statistics", () => {
    const m = shapeMetrics(g.expected.normalized);
    const [compactness, solidity, aspectRatio, diameterFill] =
      g.expected.geometry_stats;
    expect(rel(m.compactness, compactness)).toBeLessThan(1e-9);
    expect(rel(m.solidity, solidity)).toBeLessThan(1e-9);
    expect(rel(m.aspectRatio, aspectRatio)).toBeLessThan(1e-9);
    expect(rel(m.diameterFill, diameterFill)).toBeLessThan(1e-9);
  });

  it("assembles the same 20-column query vector", () => {
    const out = queryFeatureVector(g.expected.normalized, g.input.n_harmonics);
    expect(out.length).toBe(g.expected.query_vector.length);
    for (let i = 0; i < out.length; i++) {
      expect(rel(out[i], g.expected.query_vector[i])).toBeLessThan(1e-9);
    }
  });

  it("reproduces the real-index coarse shortlist from the exported static index", async () => {
    // The Phase D feasibility core: load the REAL exported index
    // (experiments/p0_7_static_export/static_index.json, 839 candidates,
    // generated by scripts/export_static_index.py from data/index) and check
    // the TS coarse stage returns the same rows and distances the Python
    // production rank() returned. The file is large and NOT committed; this
    // test self-skips (with a loud message) when the export is absent so CI
    // on a clean clone still runs — the committed golden shortlist below
    // keeps the contract alive there.
    // NOTE: vitest's jsdom environment rewrites import.meta.url to
    // http://localhost/... so file URLs cannot be used here; process.cwd()
    // is the vitest project root (web/) in every supported invocation.
    const exportPath = `${process.cwd()}/../experiments/p0_7_static_export/static_index.json`;
    let payload: {
      n_candidates: number;
      features: number[][];
      rows: { row: number; candidate_id: string }[];
    };
    try {
      // node builtins have no bundled types in this project (no @types/node);
      // the imports themselves are valid under vitest/node
      // @ts-expect-error TS2307 module resolution for the node builtin
      const { readFileSync } = await import("node:fs");
      // @ts-expect-error TS2307 module resolution for the node builtin
      const { resolve } = await import("node:path");
      payload = JSON.parse(readFileSync(resolve(exportPath), "utf-8"));
    } catch (error) {
      const code = error instanceof Error
        ? (error as { code?: string }).code
        : null;
      if (code !== "ENOENT" && code !== "ERR_MODULE_NOT_FOUND") {
        throw error;
      }
      console.warn(
        `[contract] static index export not found at ${exportPath} — ` +
          "run scripts/export_static_index.py to enable the full-library check; " +
          "asserting the committed shortlist only.",
      );
      expect(g.library.coarse.shortlist_rows).toEqual(
        [358, 144, 113, 82, 342, 234, 766, 252, 302, 84],
      );
      return;
    }
    expect(payload.n_candidates).toBe(839);
    const query = g.expected.query_vector.slice(0, g.input.n_harmonics);
    const libraryFourier = payload.features.map((row) =>
      row.slice(0, g.input.n_harmonics),
    );
    const hits = coarseShortlist(query, libraryFourier, 10);
    expect(hits.map((h) => h.row)).toEqual(g.library.coarse.shortlist_rows);
    for (let i = 0; i < hits.length; i++) {
      expect(rel(hits[i].distance, g.library.coarse.shortlist_distances[i]))
        .toBeLessThan(1e-9);
    }
    // candidate identity travels with the row
    const ids = hits.map((h) => payload.rows[h.row].candidate_id);
    expect(ids).toEqual(g.library.coarse.candidate_ids);
  });
});

describe("coarseShortlist", () => {
  it("orders by distance with stable ties by row", () => {
    const library = [
      [0.5, 0.5],
      [0.0, 0.0],
      [0.5, 0.5],
      [0.1, 0.1],
    ];
    const hits = coarseShortlist([0.0, 0.0], library, 4);
    expect(hits.map((h) => h.row)).toEqual([1, 3, 0, 2]);
    expect(hits[0].distance).toBe(0);
    // RMS distance: sqrt((0.1^2 + 0.1^2) / 2) = 0.1
    expect(hits[1].distance).toBeCloseTo(0.1, 12);
    // exact tie between rows 0 and 2: lower row first (stable argsort)
    expect(hits[2].distance).toBe(hits[3].distance);
    expect(hits[2].row).toBe(0);
  });

  it("truncates to the requested size", () => {
    const library: number[][] = Array.from({ length: 30 }, (_, i) => [i, i]);
    expect(coarseShortlist([0, 0], library, 5)).toHaveLength(5);
  });

  it("rejects a width mismatch", () => {
    expect(() => coarseShortlist([1, 2, 3], [[1, 2]], 1)).toThrow();
  });

  it("rejects an empty library", () => {
    expect(() => coarseShortlist([1], [] as number[][], 1)).toThrow();
  });
});
